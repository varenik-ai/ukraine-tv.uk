#!/usr/bin/env python3
"""CSS страниц эталона (russian-tv-site) -> assets/home.css и assets/pages.css; все селекторы под `body.<класс>`.
Запуск: python3 tools/make_ref_css.py [путь/к/russian-tv-site]"""
import re, sys, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REF = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, '..', 'russian-tv-site')
# страница эталона -> (класс <body>, файл результата)
PAGES = [('index.html', 'home', 'home.css'), ('novosti/index.html', 'cat', 'pages.css'), ('russkie-kanaly-v-germanii/index.html', 'country', 'pages.css'),
         ('about/index.html', 'static', 'pages.css'), ('russkie-kanaly-za-rubezhom/index.html', 'country', 'pages.css'), ('blog/index.html', 'blog', 'pages.css'), ('blog/kanal-ne-gruzitsya-chto-delat/index.html', 'article', 'pages.css')]
GRID_HINT = "content:'Выберите канал в списке ниже ↓'"
UA = ('body.{c}{{--accent:#005BBB;--accent2:#2f7de1;--red:#e53935}}\n'
      'body.{c} .logo .r{{color:#FFD500}}\n'
      'body.{c} .logo .b{{color:var(--accent2)}}\n')


def scope_sel(sel, cls):
    sel = sel.strip()
    if sel in (':root', 'body'):
        return 'body.' + cls
    if sel in ('*', 'html') or sel.startswith('html') or re.match(r'(body\s+)?(footer|\.footer|\.legal-note)', sel):
        return None   # футер общий для сайта (site.css)
    if sel.startswith('body '):
        return 'body.%s ' % cls + sel[5:]
    if sel.startswith('body.') or sel.startswith('body:'):
        return 'body.' + cls + sel[4:]
    return 'body.%s ' % cls + sel


def blocks(text):
    out, i, n = [], 0, len(text)
    while i < n:
        j = text.find('{', i)
        if j < 0:
            break
        depth, k = 1, j + 1
        while k < n and depth:
            depth += {'{': 1, '}': -1}.get(text[k], 0)
            k += 1
        out.append((text[i:j].strip(), text[j + 1:k - 1]))
        i = k
    return out


def scope(text, cls):
    res = []
    for pre, body in blocks(text):
        if pre.startswith('@media') or pre.startswith('@supports'):
            res.append('%s{%s}' % (pre, scope(body, cls)))
        elif pre.startswith('@'):
            res.append('%s{%s}' % (pre, body))
        else:
            sels = [x for x in (scope_sel(x, cls) for x in pre.split(',')) if x]
            if sels:
                res.append('%s{%s}' % (','.join(sels), body.strip()))
    return '\n'.join(res)


outs = {}
for path, cls, target in PAGES:
    html = open(os.path.join(REF, path), encoding='utf-8').read()
    css = '\n'.join(re.findall(r'<style[^>]*>(.*?)</style>', html, re.S))
    css = re.sub(r'/\*.*?\*/', '', css, flags=re.S)
    out = scope(css, cls).replace(GRID_HINT, 'content:var(--grid-hint)') + '\n' + UA.format(c=cls)
    outs.setdefault(target, []).append(out)
for target, parts in outs.items():
    data = '/* generated by tools/make_ref_css.py */\n' + '\n'.join(parts)
    open(os.path.join(ROOT, 'assets', target), 'w', encoding='utf-8').write(data)
    print(target, len(data), 'bytes')
